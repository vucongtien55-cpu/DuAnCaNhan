let currentLang = localStorage.getItem('novamart_lang') || 'vi';

function t(key) {
    if (translations[currentLang] && translations[currentLang][key]) {
        return translations[currentLang][key];
    }
    return translations['vi'][key] || key;
}

function setLanguage(lang) {
    if (lang === 'vi' || lang === 'en') {
        currentLang = lang;
        localStorage.setItem('novamart_lang', lang);
        applyTranslations();
        // Dispatch custom event for page listeners
        window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
    }
}

function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.innerText = t(key);
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.setAttribute('placeholder', t(key));
    });

    // Update active lang button UI
    const langBtnText = document.getElementById('langBtnText');
    if (langBtnText) {
        langBtnText.innerText = currentLang === 'vi' ? 'Tiếng Việt' : 'English';
    }
}

